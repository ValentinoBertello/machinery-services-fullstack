CREATE TABLE customers(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    maintenance_count INTEGER NOT NULL DEFAULT 0,
    maintenance_count_updated_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE maintenances(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maintenance_date TIMESTAMP WITH TIME ZONE NOT NULL,
    invoice_date TIMESTAMP WITH TIME ZONE,
    place VARCHAR(255) NOT NULL
                         CHECK (place in ('FIELD', 'WORKSHOP')),
    model VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    customer_id BIGINT NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_maintenances_customer
    FOREIGN KEY (customer_id)
    REFERENCES customers(id)
);

-- Mantenimientos activos de un cliente con rango y orden de fecha
CREATE INDEX idx_maintenances_customer_date_active
    ON maintenances(customer_id, maintenance_date)
    WHERE deleted_at IS NULL;

-- Mantenimientos activos por rango/orden de fecha (vista general, sin cliente)
CREATE INDEX idx_maintenances_date_active
    ON maintenances(maintenance_date)
    WHERE deleted_at IS NULL;

CREATE TABLE users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL unique,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    role VARCHAR(255) NOT NULL, -- Valores: 'USER', 'ADMIN'
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);